let lang = localStorage.getItem("sf-lang") || "fr";

function applyLang(l) {
  lang = l;
  localStorage.setItem("sf-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "EN" : "FR";
  document.title = l === "fr"
    ? "Plombier du Plateau Mont-Royal — Plombier à Montréal | Installation, réparation, urgence 7j/7"
    : "Plombier du Plateau Mont-Royal — Plumber in Montreal | Installation, repair, 7-day emergency";
}

